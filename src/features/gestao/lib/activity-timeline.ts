// Turns the raw rows of pm_activity_log into the events shown in a task's "Atividade": one event per action, each with
// short lines that say what changed ("Revisão → Alterações", "Responsável: Izadora"), written in plain Portuguese.
// Pure and independent of React so the wording can be tested.

export type ActivityEntry = {
  id: string;
  action: string;
  metadata: any;
  created_by: string | null;
  created_at: string;
  entity_id?: string | null;
};

export type EventKind = "created" | "stage" | "sent" | "assignee" | "date" | "done" | "cancel" | "file" | "revision" | "extra" | "status" | "fix" | "subtask";

export type EventLine = {
  kind: EventKind;
  text: string;
  /** which subtask this line is about (when the event comes from a subtask of the open task) */
  subject?: string | null;
};

export type TimelineEvent = {
  id: string;
  at: string;
  actorId: string | null;
  lines: EventLine[];
};

export type ActivityContext = {
  /** the task whose Atividade is open: events about its subtasks carry the subtask title */
  taskId: string;
  stageName: (key: string) => string;
  statusName: (key: string) => string;
  memberName: (id: string) => string | null;
  /** position of a stage in the pipeline, to tell "avançou" from "voltou" (unknown stages: -1) */
  stageIndex: (key: string) => number;
  /** this task was generated from a previous stage (it has an origin) but its log predates the richer "created" record */
  derived?: boolean;
};

const MERGE_WINDOW_MS = 5000;

function isoToBr(value: unknown): string {
  const [y, m, d] = String(value).slice(0, 10).split("-");
  return y && m && d ? `${d}/${m}/${y}` : String(value);
}

function plural(n: number, one: string, many: string) {
  return `${n} ${n === 1 ? one : many}`;
}

/** The "created" row of a task that was generated by advancing a stage, or created from scratch. */
function createdLines(m: any, ctx: ActivityContext): EventLine[] {
  if (m?.parent_task_id) return [{ kind: "subtask", text: `criou a subtarefa “${m.title ?? ""}”` }];
  if (m?.from_stage) {
    const subs = Number(m.subtasks ?? 0);
    return [{
      kind: "sent",
      text: `enviou de ${ctx.stageName(m.from_stage)} para ${ctx.stageName(m.to_stage ?? m.stage_current)}${subs > 0 ? ` · ${plural(subs, "subtarefa", "subtarefas")}` : ""}`,
    }];
  }
  if (m?.stage_current) return [{ kind: "created", text: `criou esta tarefa em ${ctx.stageName(m.stage_current)}` }];
  if (ctx.derived) return [{ kind: "created", text: "esta etapa foi criada ao avançar da etapa anterior" }];
  return [{ kind: "created", text: "criou esta tarefa" }];
}

function updatedLines(m: any, ctx: ActivityContext, lastStage: string | null, subject: string | null): EventLine[] {
  const lines: EventLine[] = [];
  const push = (kind: EventKind, text: string) => lines.push({ kind, text, subject });

  if (m?.status_global === "concluido") push("done", "marcou como concluída");
  else if (m?.status_global === "cancelado") push("cancel", "cancelou a tarefa");

  if (m?.stage_current) {
    const from = m._from_stage ?? lastStage;
    const to = m.stage_current;
    if (from && from !== to) {
      const back = ctx.stageIndex(from) > ctx.stageIndex(to) && ctx.stageIndex(to) >= 0;
      push("stage", `${back ? "voltou" : "avançou"} de ${ctx.stageName(from)} para ${ctx.stageName(to)}`);
    } else {
      push("stage", `moveu para ${ctx.stageName(to)}`);
    }
  }
  if (m && Object.prototype.hasOwnProperty.call(m, "assignee_id")) {
    const name = m.assignee_id ? ctx.memberName(m.assignee_id) ?? "alguém" : null;
    push("assignee", name ? `Responsável: ${name}` : "Removeu o responsável");
  }
  if (m && Object.prototype.hasOwnProperty.call(m, "due_date") && m.due_date !== undefined) {
    push("date", m.due_date ? `Data: ${isoToBr(m.due_date)}` : "Removeu a data");
  }
  if (m?._revision_change) {
    const rc = m._revision_change;
    const label = rc.newStatus === "aprovado" ? "aprovada" : rc.newStatus === "alteracao" ? "pediu alteração" : "voltou para pendente";
    push("revision", `“${rc.childTitle}” ${label}`);
  }
  if (m?.is_extra_demand !== undefined) push("extra", m.is_extra_demand ? "Marcou como extra" : "Tirou a marca de extra");
  if (m?.status_global && m.status_global !== "concluido" && m.status_global !== "cancelado") push("status", `Status: ${ctx.statusName(m.status_global)}`);
  return lines;
}

/** Several subtasks getting the same change at once ("PDF → Design" ×11) become one line instead of eleven. */
function collapseSubjects(lines: EventLine[]): EventLine[] {
  const groups = new Map<string, EventLine[]>();
  const order: (EventLine | string)[] = [];
  for (const l of lines) {
    if (!l.subject) { order.push(l); continue; }
    const key = `${l.kind}|${l.text}`;
    if (!groups.has(key)) { groups.set(key, []); order.push(key); }
    groups.get(key)!.push(l);
  }
  const out: EventLine[] = [];
  for (const item of order) {
    if (typeof item !== "string") { out.push(item); continue; }
    const g = groups.get(item)!;
    if (g.length <= 2) out.push(...g);
    else out.push({ kind: g[0].kind, text: g[0].text, subject: `${g.length} subtarefas` });
  }
  return out;
}

export function buildActivityEvents(entries: ActivityEntry[], ctx: ActivityContext): TimelineEvent[] {
  const sorted = [...entries].sort((a, b) => new Date(a.created_at).getTime() - new Date(b.created_at).getTime());
  const seen = new Set<string>();
  const events: TimelineEvent[] = [];
  let lastStage: string | null = null;

  for (const e of sorted) {
    if (e.action === "comment_added") continue;
    // the same write can be logged twice a moment apart
    const key = `${e.action}:${e.created_by}:${JSON.stringify(e.metadata)}:${Math.floor(new Date(e.created_at).getTime() / 2000)}`;
    if (seen.has(key)) continue;
    seen.add(key);

    const m = e.metadata ?? {};
    const isChild = !!m.task_id && m.task_id !== ctx.taskId && e.entity_id === ctx.taskId;
    const subject = isChild ? (m._ref_title ?? "subtarefa") : null;
    let lines: EventLine[] = [];

    switch (e.action) {
      case "created":
        lines = createdLines(m, ctx);
        if (!isChild && !m.parent_task_id) lastStage = m.to_stage ?? m.stage_current ?? lastStage;
        break;
      case "stage_sent":
        lines = [{ kind: "sent", text: `concluiu ${ctx.stageName(m.from_stage)} e enviou para ${ctx.stageName(m.to_stage)}${Number(m.subtasks ?? 0) > 0 ? ` · ${plural(Number(m.subtasks), "subtarefa", "subtarefas")}` : ""}` }];
        break;
      case "stage_received":
        lines = createdLines({ from_stage: m.from_stage, to_stage: m.to_stage, subtasks: m.subtasks }, ctx);
        lastStage = m.to_stage ?? lastStage;
        break;
      case "updated":
        lines = updatedLines(m, ctx, isChild ? null : lastStage, subject);
        if (!isChild && m.stage_current) lastStage = m.stage_current;
        break;
      case "correction_tags": lines = [{ kind: "fix", text: "corrigiu as etiquetas (tarefa já concluída)" }]; break;
      case "correction_assignee": lines = [{ kind: "fix", text: "corrigiu o responsável (tarefa já concluída)" }]; break;
      case "file_added": lines = [{ kind: "file", text: `anexou ${m.file_name ?? "um arquivo"}` }]; break;
      default: break; // everything else is noise for the team
    }
    if (lines.length === 0) continue;
    events.push({ id: e.id, at: e.created_at, actorId: e.created_by ?? null, lines });
  }

  // one person's changes made within a few seconds read as a single event
  const merged: TimelineEvent[] = [];
  for (const ev of events) {
    const prev = merged[merged.length - 1];
    if (prev && prev.actorId === ev.actorId && new Date(ev.at).getTime() - new Date(prev.at).getTime() <= MERGE_WINDOW_MS) {
      prev.lines = [...prev.lines, ...ev.lines];
    } else {
      merged.push({ ...ev, lines: [...ev.lines] });
    }
  }
  return merged.map((ev) => ({ ...ev, lines: collapseSubjects(ev.lines) }));
}

/** "Hoje", "Ontem" or "13 de out." for the day headers. */
export function dayLabel(iso: string, now: Date = new Date()): string {
  const d = new Date(iso);
  const startOf = (x: Date) => new Date(x.getFullYear(), x.getMonth(), x.getDate()).getTime();
  const diffDays = Math.round((startOf(now) - startOf(d)) / 86_400_000);
  if (diffDays === 0) return "Hoje";
  if (diffDays === 1) return "Ontem";
  return d.toLocaleDateString("pt-BR", { day: "numeric", month: "short", ...(d.getFullYear() !== now.getFullYear() ? { year: "numeric" } : {}) });
}
